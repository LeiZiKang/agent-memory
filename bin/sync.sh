#!/bin/bash
# Copy RULES.md into ~/.codex/AGENTS.md between markers (Codex has no @import).
# Claude Code reads RULES.md through an @import line in ~/.claude/CLAUDE.md, so it needs no sync.
# Re-run after editing RULES.md.
set -e
HOME_DIR="${AGENT_MEMORY_HOME:-$HOME/.config/agent-memory}"
RULES="$HOME_DIR/RULES.md"
AGENTS="${CODEX_HOME:-$HOME/.codex}/AGENTS.md"
BEGIN='<!-- agent-memory:begin (generated by agent-memory sync.sh; edit RULES.md and re-sync) -->'
mkdir -p "$(dirname "$AGENTS")"; touch "$AGENTS"
tmp=$(mktemp)
# drop the old block, then trailing blank lines
awk 'index($0,"agent-memory:begin"){skip=1} !skip{print} index($0,"agent-memory:end"){skip=0}' "$AGENTS" |
  sed -e :a -e '/^\n*$/{$d;N;ba' -e '}' > "$tmp"
{ cat "$tmp"; [ -s "$tmp" ] && echo; echo "$BEGIN"; cat "$RULES"; echo '<!-- agent-memory:end -->'; } > "$AGENTS"
rm "$tmp"
echo "synced $RULES -> $AGENTS"
